// 重點文字沒有天生的唯一 id，用「關卡 id + 陣列索引」組出穩定識別碼給收藏功能存
export const keyPointId = (levelId: string, index: number): string => `${levelId}:${index}`

export interface SavedKeyPoint {
  id: string
  text: string
  chapterId: string
  chapterTitle: string
  levelTitle: string
}

// 收藏重點清單用：只存 id（Record<string, boolean>），畫面顯示的文字/章節資訊都即時從
// chapterSummaries／chapters 查回來，不用在收藏紀錄裡另外存一份文字快照
export const getSavedKeyPoints = (savedKeyPointIds: Record<string, boolean>): SavedKeyPoint[] => {
  const result: SavedKeyPoint[] = []
  for (const chapter of chapters) {
    const summaries = chapterSummaries[chapter.id]
    if (!summaries) continue
    for (const summary of summaries) {
      const level = chapter.levels.find((l) => l.id === summary.levelId)
      summary.keyPoints.forEach((text, index) => {
        const id = keyPointId(summary.levelId, index)
        if (savedKeyPointIds[id]) {
          result.push({ id, text, chapterId: chapter.id, chapterTitle: chapter.title, levelTitle: level?.title ?? summary.levelId })
        }
      })
    }
  }
  return result
}
